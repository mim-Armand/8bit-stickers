#!/usr/bin/env python3
"""Build a dependency-free catalog for the local studio from the native assets."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACK = ROOT / '8 bit art StickerPackExtension/Stickers.xcstickers/Sticker Pack.stickerpack'
TITLES = {
    'exclamation_point_01': ('Surprise block', ['surprise', 'retro']),
    'banana_01': ('Banana', ['fruit', 'snack']),
    'hear_01': ('Original heart', ['love', 'heart']),
    'pumpkin_01': ('Pumpkin', ['halloween', 'autumn']),
    'skull_01': ('Skull', ['spooky', 'halloween']),
    'ghost_01': ('Little ghost', ['spooky', 'boo']),
    'flower_01': ('Flower', ['nature', 'bloom']),
    'smiley_01': ('Happy face', ['happy', 'smile']),
    'smiley_02': ('Big grin', ['happy', 'smile']),
    'dealwithit_01': ('Pixel shades', ['cool', 'sunglasses']),
    'wine_01': ('Wine glass', ['cheers', 'drink']),
}
items = []
for entry in json.loads((PACK / 'Contents.json').read_text())['stickers']:
    folder = PACK / entry['filename']
    stem = folder.stem
    if stem not in TITLES:
        continue
    filename = json.loads((folder / 'Contents.json').read_text())['properties']['filename']
    title, tags = TITLES[stem]
    items.append(dict(id=stem, title=title, category='Originals', tags=tags,
                      preview=str((folder / filename).relative_to(ROOT)),
                      filename=str((folder / filename).relative_to(ROOT)), animated=False, original=True))
manifest = ROOT / 'art/manifest.json'
if manifest.exists():
    fresh = [{**item, 'original': False} for item in json.loads(manifest.read_text())['stickers']]
    # Surface the seven newest reactions while retaining stable order within each batch.
    fresh.sort(key=lambda item: 0 if item.get('source', '').startswith('art/club67-')
               else 1 if item.get('collection') == 'tiny-pixels' else 2)
    items = fresh + items
out = ROOT / 'prototype/catalog.js'
out.parent.mkdir(exist_ok=True)
out.write_text('/* Generated by scripts/build-preview.py. */\nwindow.STICKERS = ' + json.dumps(items, indent=2) + ';\n')
print(f'Built studio catalog: {len(items)} stickers → {out.relative_to(ROOT)}')
