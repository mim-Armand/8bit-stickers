#!/usr/bin/env python3
"""Build a dependency-free catalogue for the local Studio from tracked assets."""
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('catalog_source', ROOT / 'scripts/catalog-source.py')
source = importlib.util.module_from_spec(spec)
spec.loader.exec_module(source)
items = source.load_catalog()
items.sort(key=lambda item: 3 if item['original']
           else 0 if item.get('source', '').startswith('art/club67-')
           else 1 if item.get('collection') == 'tiny-pixels' else 2)
out = ROOT / 'prototype/catalog.js'
out.write_text('/* Generated by scripts/build-preview.py. */\nwindow.STICKERS = ' + json.dumps(items, indent=2) + ';\n')
print(f'Built studio catalog: {len(items)} stickers → {out.relative_to(ROOT)}')
